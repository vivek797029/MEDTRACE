    "        if global_weights is not None:\n",
    "            model.load_state_dict(global_weights, strict=False)\n",
    "        model.to(device).train()\n",
    "\n",
    "        def tokenize_fn(examples):\n",
    "            prompts = [\n",
    "                f'<|system|>\\n{SYSTEM_MSG}</s>\\n<|user|>\\n{q}</s>\\n<|assistant|>\\n'\n",
