    "\n",
    "device = 'cuda' if torch.cuda.is_available() else 'cpu'\n",
    "\n",
    "\n",
    "# ── Adaptive DP State ──────────────────────────────────────────────────────\n",
    "class ClientDPState:\n",
    "    def __init__(self, hospital_id, init_sensitivity=1.0):\n",
    "        self.hospital_id    = hospital_id\n",
    "        self.sensitivity_ema = init_sensitivity\n",
    "        self.budget_spent   = 0.0\n",
    "        self.latest_loss    = float('inf')\n",
    "        self.round_epsilons = []\n",
    "\n",
    "    def record_loss(self, loss):   self.latest_loss = float(loss)\n",
    "    def update_sensitivity(self, norm, alpha):\n",
    "        self.sensitivity_ema = alpha * norm + (1.0 - alpha) * self.sensitivity_ema\n",
    "\n",
    "\n",
    "class AdaptiveDPMechanism:\n",
    "    \"\"\"\n",
    "    Per-client noise calibration.\n",
    "    Converged hospitals (low loss) get more ε → less noise → cleaner updates.\n",
    "    \"\"\"\n",
    "    def __init__(self, hospital_ids, global_eps, delta, fl_rounds,\n",
    "                 init_sensitivity=1.0, ema_alpha=0.1, min_frac=0.1):\n",
    "        self.global_epsilon = global_eps\n",
    "        self.delta      = delta\n",
    "        self.fl_rounds  = fl_rounds\n",
    "        self.ema_alpha  = ema_alpha\n",
    "        self.min_frac   = min_frac\n",
    "        self.states = {hid: ClientDPState(hid, init_sensitivity) for hid in hospital_ids}\n",
    "        print(f'Adaptive DP: ε={global_eps} δ={delta} α={ema_alpha} floor={min_frac}')\n",
    "\n",
    "    def compute_allocation(self, round_num):\n",
    "        base_eps = self.global_epsilon / math.sqrt(self.fl_rounds)\n",
    "        losses = {hid: s.latest_loss for hid, s in self.states.items()}\n",
    "        # Softmax over inverse loss (low loss → high weight → more ε)\n",
    "        inv = {hid: (1.0 / l if l > 0 and l != float('inf') else 1.0)\n",
    "               for hid, l in losses.items()}\n",
    "        total_inv = sum(inv.values())\n",
    "        weights   = {hid: v / total_inv for hid, v in inv.items()}\n",
    "        n = len(self.states)\n",
    "        alloc = {}\n",
    "        for hid, w in weights.items():\n",
    "            s = self.states[hid]\n",
    "            eps = max(base_eps * n * w, base_eps * self.min_frac)\n",
    "            remaining = max(0.0, self.global_epsilon - s.budget_spent)\n",
    "            alloc[hid] = min(eps, remaining)\n",
    "        return alloc\n",
    "\n",
    "    def apply_noise(self, hospital_id, weights, round_num, round_epsilon):\n",
    "        state = self.states[hospital_id]\n",
    "        if round_epsilon <= 0.0:\n",
    "            print(f'  {hospital_id}: budget exhausted, returning unnoised weights')\n",
    "            return weights\n",
    "        clip_norm = state.sensitivity_ema\n",
    "        sigma = clip_norm * math.sqrt(2.0 * math.log(1.25 / self.delta)) / round_epsilon\n",
    "\n",
    "        with torch.no_grad():\n",
    "            flat = torch.cat([p.reshape(-1).float() for p in weights.values()])\n",
    "            actual_norm = torch.norm(flat).item()\n",
    "        state.update_sensitivity(actual_norm, self.ema_alpha)\n",
    "\n",
    "        noisy = OrderedDict()\n",
    "        with torch.no_grad():\n",
    "            for name, param in weights.items():\n",
    "                p = param.float()\n",
    "                norm = torch.norm(p).item()\n",
    "                if norm > clip_norm and norm > 0:\n",
    "                    p = p * (clip_norm / norm)\n",
    "                noisy[name] = p + torch.randn_like(p) * sigma\n",
    "\n",
    "        state.budget_spent += round_epsilon\n",
    "        state.round_epsilons.append(round_epsilon)\n",
    "        print(f'  Adaptive DP | Cᵢ={clip_norm:.3f} σ={sigma:.4f} ε_r={round_epsilon:.4f} '\n",
    "              f'spent={state.budget_spent:.3f}/{self.global_epsilon}')\n",
    "        return noisy\n",
    "\n",
    "    def record_loss(self, hospital_id, loss):\n",
    "        self.states[hospital_id].record_loss(loss)\n",
    "\n",
    "    def summary(self):\n",
    "        return {\n",
    "            hid: {'budget_spent': s.budget_spent, 'sensitivity_ema': s.sensitivity_ema,\n",
    "                  'latest_loss': s.latest_loss, 'rounds': len(s.round_epsilons)}\n",
    "            for hid, s in self.states.items()\n",
    "        }\n",
    "\n",
    "\n",
    "# ── Hospital Client ────────────────────────────────────────────────────────\n",
    "class HospitalClient:\n",
    "    def __init__(self, hospital_id, config):\n",
    "        self.hid          = hospital_id\n",
    "        self.name         = config['name']\n",
    "        self.location     = config['location']\n",
    "        self.keywords     = config['keywords']\n",
    "        self.num_samples  = config['num_samples']\n",
    "        self.spec_ratio   = config['specialty_ratio']\n",
    "        self.local_data   = None\n",
    "        self.budget_spent = 0.0\n",
    "        self.round_losses = []\n",
    "        print(f'  ✓ {self.name} ({self.location})')\n",
    "\n",
    "    def prepare_data(self, full_dataset, round_num):\n",
    "        pattern = re.compile('|'.join(re.escape(k) for k in self.keywords), re.IGNORECASE)\n",
    "        spec_idx, gen_idx = [], []\n",
    "        for i, ex in enumerate(full_dataset):\n",
    "            (spec_idx if pattern.search(ex.get('question', '')) else gen_idx).append(i)\n",
    "\n",
    "        seed = abs(hash(self.hid) + round_num) % (2**32)\n",
    "        rng  = np.random.RandomState(seed)\n",
    "        n = min(self.num_samples, len(full_dataset))\n",
    "        n_spec = min(int(n * self.spec_ratio), len(spec_idx))\n",
    "        n_gen  = n - n_spec\n",
    "\n",
    "        chosen = []\n",
    "        if n_spec > 0 and spec_idx: chosen.extend(rng.choice(spec_idx, n_spec, replace=True))\n",
    "        if n_gen  > 0 and gen_idx:  chosen.extend(rng.choice(gen_idx,  n_gen,  replace=True))\n",
    "        if not chosen: chosen = rng.choice(len(full_dataset), n, replace=True).tolist()\n",
    "        rng.shuffle(chosen)\n",
    "        self.local_data = full_dataset.select(chosen[:n])\n",
    "        print(f'  {self.name}: {len(self.local_data)} samples ({n_spec} specialty, {n_gen} general)')\n",
    "\n",
    "    def _make_lora_config(self):\n",
    "        return LoraConfig(r=LORA_R, lora_alpha=LORA_ALPHA, lora_dropout=0.05,\n",
    "                          target_modules=LORA_TARGETS, bias='none', task_type='CAUSAL_LM')\n",
    "\n",
    "    def train_local(self, global_weights, tokenizer, round_num,\n",
    "                    base_model=None, adaptive_dp=None, round_epsilon=None):\n",
    "        print(f'\\n  ── {self.name} | Round {round_num+1} ──')\n",
    "        t0 = time.time()\n",
    "\n",
    "        owns_base = base_model is None\n",
    "        if owns_base:\n",
    "            base_model = AutoModelForCausalLM.from_pretrained(\n",
    "                BASE_MODEL, torch_dtype=torch.float32)\n",
