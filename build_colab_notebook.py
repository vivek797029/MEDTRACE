    "        tok_data = self.local_data.map(tokenize_fn, batched=True,\n",
    "                                       remove_columns=self.local_data.column_names)\n",
    "        tok_data.set_format('torch')\n",
    "\n",
    "        out_dir = f'/content/fl_temp/{self.hid}/round_{round_num}'\n",
    "        os.makedirs(out_dir, exist_ok=True)\n",
    "\n",
    "        args = TrainingArguments(\n",
    "            output_dir=out_dir,\n",
    "            num_train_epochs=LOCAL_EPOCHS,\n",
    "            per_device_train_batch_size=BATCH_SIZE,\n",
    "            gradient_accumulation_steps=GRAD_ACCUM,\n",
    "            learning_rate=LR,\n",
    "            warmup_steps=10,\n",
    "            weight_decay=0.01,\n",
    "            logging_steps=10,\n",
    "            save_strategy='no',\n",
    "            report_to='none',\n",
    "            fp16=torch.cuda.is_available(),\n",
    "            gradient_checkpointing=True,\n",
    "            dataloader_pin_memory=False,\n",
    "        )\n",
    "        trainer = Trainer(\n",
    "            model=model, args=args, train_dataset=tok_data,\n",
    "            data_collator=DataCollatorForLanguageModeling(tokenizer, mlm=False),\n",
    "        )\n",
    "        trainer.train()\n",
    "        elapsed = time.time() - t0\n",
    "\n",
    "        # Extract LoRA weights\n",
    "        lora_w = OrderedDict(\n",
    "            (name, p.detach().cpu().clone())\n",
    "            for name, p in model.named_parameters() if 'lora_' in name\n",
    "        )\n",
    "\n",
    "        # Apply DP noise\n",
    "        use_adaptive = ADAPTIVE_DP and adaptive_dp is not None and round_epsilon is not None\n",
    "        if use_adaptive:\n",
    "            lora_w = adaptive_dp.apply_noise(self.hid, lora_w, round_num, round_epsilon)\n",
    "            self.budget_spent = adaptive_dp.states[self.hid].budget_spent\n",
    "        elif DP_ENABLED:\n",
    "            with torch.no_grad():\n",
    "                for name in lora_w:\n",
    "                    p = lora_w[name].float()\n",
    "                    norm = torch.norm(p).item()\n",
    "                    if norm > DP_MAX_GRAD_NORM:\n",
    "                        p = p * (DP_MAX_GRAD_NORM / norm)\n",
    "                    lora_w[name] = p + torch.randn_like(p) * DP_SIGMA\n",
    "            per_round_eps = DP_EPSILON / math.sqrt(FL_ROUNDS)\n",
    "            self.budget_spent += per_round_eps\n",
    "            print(f'  Standard DP | σ={DP_SIGMA:.4f} | Budget: {self.budget_spent:.3f}/{DP_EPSILON}')\n",
    "\n",
    "        train_loss = (\n",
    "            trainer.state.log_history[-1].get('train_loss', 0.0)\n",
